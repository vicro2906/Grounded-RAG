def _describe_schema() -> dict:
    return {
        "name": "descriptions",
        "strict": True,
        "schema": {
            "type": "object",
            "additionalProperties": False,
            "required": ["descriptions"],
            "properties": {
                "descriptions": {
                    "type": "array",
                    "items": {
                        "type": "object",
                        "additionalProperties": False,
                        "required": ["index", "text"],
                        "properties": {"index": {"type": "integer"},
                                       "text": {"type": "string"}},
                    },
                }
            },
        },
    }


def _items_by_chunk() -> dict[str, list]:
    """Group every node and edge under the chunks it was extracted from, so each LLM call can
    describe a whole chunk's items while reading that chunk once."""
    graph = _get_store().graph
    by_chunk: dict[str, list] = {}
    for node, attrs in graph.nodes(data=True):
        for cid in _chunk_ids_of(attrs):
            by_chunk.setdefault(cid, []).append(node)
    for u, v, attrs in graph.edges(data=True):
        for cid in _chunk_ids_of(attrs):
            by_chunk.setdefault(cid, []).append((u, v))
    return by_chunk


async def _describe_chunk(cid: str, text: str, items: list,
                          semaphore) -> dict:
    """Describe one chunk's items in Spanish. A failure yields nothing for that chunk: those
    items keep LightRAG's English description (`_describe` falls back)."""
    listing = "\n".join(
        f"{i}. {it if isinstance(it, str) else f'{it[0]} ↔ {it[1]}'}"
        for i, it in enumerate(items)
    )
    async with semaphore:
        try:
            response = await asyncio.to_thread(
                client.chat.completions.create,
                model=REPHRASE_MODEL,
                temperature=0,
                messages=[{"role": "system", "content": _DESCRIBE_SYS},
                          {"role": "user",
                           "content": f"FRAGMENTO:\n{text}\n\nELEMENTOS:\n{listing}"}],
                response_format={"type": "json_schema", "json_schema": _describe_schema()},
            )
            data = json.loads(response.choices[0].message.content)
            out = {}
            for d in data["descriptions"]:
                i = d["index"]
                if 0 <= i < len(items) and d["text"].strip():
                    out[_item_key(items[i])] = d["text"].strip()
        except Exception as exc:
            print(f"  ! {cid}: {type(exc).__name__}")
            out = {}
    return {"chunk_id": cid, "descriptions": out}


async def _generate_descriptions_es() -> None:
    """Regenerate every node/edge description in Spanish from its source chunk. Resumable at
    the chunk level (append-only JSONL), like the other index builds."""
    from ._common import load_chunks

    chunks = {c["chunk_id"]: c for c in load_chunks()}
    by_chunk = _items_by_chunk()
    done = set()
    if os.path.isfile(DESCRIPTIONS_ES):
        with open(DESCRIPTIONS_ES, encoding="utf-8") as fh:
            done = {json.loads(l)["chunk_id"] for l in fh if l.strip()}
    todo = [c for c in by_chunk if c in chunks and c not in done]
    total_items = sum(len(by_chunk[c]) for c in todo)
    print(f"Spanish descriptions: {len(done)} chunks done, {len(todo)} to go "
          f"({total_items} items).")
    if not todo:
        return

    semaphore = asyncio.Semaphore(OPENIE_CONCURRENCY)

    async def describe_all(cid: str) -> dict:
        """One chunk, in batches — the results are written as a single resumable record."""
        items = by_chunk[cid]
        batches = [items[i:i + DESCRIBE_BATCH] for i in range(0, len(items), DESCRIBE_BATCH)]
        parts = await asyncio.gather(
            *[_describe_chunk(cid, chunks[cid]["text"], b, semaphore) for b in batches])
        merged: dict[str, str] = {}
        for p in parts:
            merged.update(p["descriptions"])
        return {"chunk_id": cid, "descriptions": merged}

    tasks = [asyncio.create_task(describe_all(c)) for c in todo]
    described = 0
    with open(DESCRIPTIONS_ES, "a", encoding="utf-8") as fh:
        for i, task in enumerate(asyncio.as_completed(tasks), 1):
            record = await task
            described += len(record["descriptions"])
            fh.write(json.dumps(record, ensure_ascii=False) + "\n")
            fh.flush()
            if i % 25 == 0 or i == len(todo):
                print(f"  {i}/{len(todo)} chunks · {described}/{total_items} items described")
    print(f"Written to {DESCRIPTIONS_ES}")


