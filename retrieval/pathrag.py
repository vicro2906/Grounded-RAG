# STORE  (the only code that knows lightrag-hku's on-disk layout)
# ---------------------------------------------------------------------------
@dataclass
class _PathStore:
    """The LightRAG index as PathRAG needs it: a walkable graph, node embeddings to match the
    query against, and the mapping back to our citable chunks."""
    graph: "object"                       # networkx.Graph (undirected entity graph)
    node_names: list[str]                 # row i of `node_emb` describes node_names[i]
    node_emb: np.ndarray                  # (n_nodes, 3072), L2-normalized
    node_row: dict[str, int] = field(default_factory=dict)
    lr_to_chunk: dict[str, str] = field(default_factory=dict)  # LightRAG chunk id -> our chunk_id
    desc_es: dict[str, str] = field(default_factory=dict)      # item key -> Spanish description


def _decode_matrix(vdb: dict) -> np.ndarray:
    """LightRAG stores the vectors as ONE base64 float32 blob, row-aligned with `data`."""
    dim = int(vdb["embedding_dim"])
    rows = len(vdb["data"])
    raw = base64.b64decode(vdb["matrix"])
    expected = rows * dim * 4
    if len(raw) != expected:
        raise SystemExit(
            f"{VDB_ENTITIES}: unexpected matrix size ({len(raw)} bytes, expected {expected} "
            f"for {rows}x{dim} float32). The lightrag-hku store layout changed — update "
            f"_PathStore in retrieval/pathrag.py."
        )
    return np.frombuffer(raw, dtype=np.float32).reshape(rows, dim)


def _build_store() -> _PathStore:
    import networkx as nx

    for path in (GRAPHML, VDB_ENTITIES, TEXT_CHUNKS):
        if not os.path.isfile(path):
            raise SystemExit(
                f"{path} not found. PathRAG reads the LightRAG index; build it first: "
                f".venv\\Scripts\\python.exe -m retrieval.graph"
            )

    graph = nx.read_graphml(GRAPHML)

    with open(VDB_ENTITIES, encoding="utf-8") as fh:
        vdb = json.load(fh)
    if int(vdb["embedding_dim"]) != EMBEDDING_DIM:
        raise SystemExit(
            f"{VDB_ENTITIES}: embedding_dim {vdb['embedding_dim']} != {EMBEDDING_DIM}. "
            f"The index was built with a different embedding model."
        )
    emb = _decode_matrix(vdb)                       # already L2-normalized by LightRAG
    names = [d.get("entity_name", "") for d in vdb["data"]]

    # Each chunk was inserted as its own LightRAG document keyed by OUR chunk_id, so a
    # LightRAG chunk's `full_doc_id` IS our chunk_id — this is the bridge from the graph's
    # source_id back to citable payloads. (535 LightRAG chunks -> 517 of ours: a few long
    # chunks were split, several mapping to the same payload.)
    with open(TEXT_CHUNKS, encoding="utf-8") as fh:
        text_chunks = json.load(fh)
    lr_to_chunk = {lr_id: v["full_doc_id"] for lr_id, v in text_chunks.items()
                   if v.get("full_doc_id")}

    return _PathStore(graph=graph, node_names=names, node_emb=emb,
                      node_row={n: i for i, n in enumerate(names)},
                      lr_to_chunk=lr_to_chunk, desc_es=_load_descriptions_es())


_store: _PathStore | None = None
_store_lock = threading.Lock()
def _get_store() -> _PathStore:
    """Load the store once (double-checked locking: retrieval runs branches in parallel)."""
    global _store
    if _store is None:
        with _store_lock:
            if _store is None:
                _store = _build_store()
    return _store


def _chunk_ids_of(attrs: dict) -> list[str]:
    """Our chunk_ids behind a node/edge, via its LightRAG source_id field."""
    store = _get_store()
    raw = attrs.get("source_id") or ""
    return [store.lr_to_chunk[p] for p in raw.split(SEP) if p in store.lr_to_chunk]


# ---------------------------------------------------------------------------
# SPANISH DESCRIPTIONS  (python -m retrieval.pathrag --describe-es)
# ---------------------------------------------------------------------------
# LightRAG's extraction prompt is English, so it described a Spanish corpus in English: 84% of
# node and 70% of edge descriptions. That is harmless for the `graph` mode (there the
# descriptions only match embeddings and are then discarded) but not for PathRAG, whose
# concept map puts that text in front of a generator answering in Spanish about Spanish
# guidelines. Rather than re-extract the whole graph in Spanish (~1.5 h, and it would
# invalidate the graph mode's measured index), we regenerate ONLY the descriptions, reading
# the source chunk so they gain clinical content instead of being a mere translation.
_ITEM_SEP = "\x00"          # joins the two endpoints into one edge key


def _item_key(item) -> str:
    """Stable key for a node (its name) or an edge (both endpoints, order-independent)."""
    return item if isinstance(item, str) else _ITEM_SEP.join(sorted(item))


def _load_descriptions_es() -> dict[str, str]:
    """Load the generated Spanish descriptions.

    A concept usually appears in several chunks and is therefore described several times, from
    each chunk's angle. We keep ONE description per item, resolved by chunk_id order: the
    records are written as the async tasks finish (non-deterministic), so without sorting the
    same index would describe «TAF» differently on each build."""
    if not os.path.isfile(DESCRIPTIONS_ES):
        return {}
    with open(DESCRIPTIONS_ES, encoding="utf-8") as fh:
        records = [json.loads(line) for line in fh if line.strip()]
    out: dict[str, str] = {}
    for rec in sorted(records, key=lambda r: r["chunk_id"]):
        for key, text in rec.get("descriptions", {}).items():
            out.setdefault(key, text)          # first chunk wins, deterministically
    return out


# ---------------------------------------------------------------------------
# STAGE 2: node retrieval
# ---------------------------------------------------------------------------
def retrieve_nodes(keywords: list[str], top_n: int = NODE_TOP_N) -> dict[str, float]:
    """Match the keywords against the entity embeddings; return {node: relevance} for the
    top_n distinct CONCEPTS.

    Distinct concepts, not distinct nodes: the index holds up to seven spellings of «TAR», and
    without collapsing them by `canonical_key` they alone would fill a sixth of the budget,
    starving the concepts that actually discriminate the question (measured: the top-40 for an
    HBV question was mostly TAR variants). Keywords are abbreviation-expanded so «DTG» matches
    a node written «dolutegravir».

    The similarity is RETURNED, not discarded: path reliability needs it to stay anchored to
    the question (see `retrieve_paths`)."""
    store = _get_store()
    vecs = []
    for kw in keywords:
        try:
            v = np.asarray(get_embedding(expand_abbrevs(kw)), dtype=np.float32)
            vecs.append(v / (np.linalg.norm(v) or 1.0))
        except Exception:
            continue
    if not vecs:
        return {}
    # Best score across keywords per node (a node is relevant if ANY keyword matches it),
    # rather than an average that would dilute a strong single-keyword hit.
    sims = (store.node_emb @ np.vstack(vecs).T).max(axis=1)
    out, seen = {}, set()
    for i in np.argsort(-sims):
        name = store.node_names[i]
        key = canonical_key(name)
        if name in store.graph and key not in seen:
            seen.add(key)
            out[name] = float(sims[i])
            if len(out) >= top_n:
                break
    return _rescale(out)


def _rescale(scores: dict[str, float], floor: float = 0.1) -> dict[str, float]:
    """Spread the similarities over [floor, 1] by min-max over the retrieved set.

    Raw cosines from text-embedding-3-large sit in a narrow band (0.60-0.68 measured across a
    top-40), so multiplying by them barely reorders anything next to a flow value ranging
    1.00-1.70 — the correction would be nominal. Rescaling relative to the candidates actually
    retrieved gives relevance the same discriminating power as flow. The floor keeps the last
    candidate from collapsing to zero, which would erase every path touching it."""
    if not scores:
        return {}
    lo, hi = min(scores.values()), max(scores.values())
    if hi - lo < 1e-9:
        return {k: 1.0 for k in scores}
    return {k: floor + (1 - floor) * (v - lo) / (hi - lo) for k, v in scores.items()}


# ---------------------------------------------------------------------------
# STAGE 3: path retrieval (flow-based pruning with distance awareness)
# ---------------------------------------------------------------------------
@dataclass
class _Path:
    nodes: list[str]
    flow: float          # S(P) from the paper: how strongly the endpoints are connected
    relevance: float     # how close the path's endpoints are to the question (cosine)

    @property
    def score(self) -> float:
        """Final ranking score. See `retrieve_paths` for why flow alone is not enough."""
        return self.flow * self.relevance


def _flow_paths(start: str, targets: set[str], decay: float, threshold: float,
                max_hops: int) -> list[_Path]:
    """Propagate one unit of resource from `start` and collect the paths that reach another
    retrieved node (eq. 2-4 of the paper).

    Resource flowing into a node is its predecessor's resource, decayed by `decay` and split
    across that predecessor's neighbours — so distant and highly-connected (i.e. generic)
    nodes contribute little, which is exactly the redundancy PathRAG set out to prune. A
    branch dies as soon as its resource falls below `threshold`. The flow value is the sum of
    the resources along the path, normalized by the number of edges (eq. 4)."""
    graph = _get_store().graph
    paths: list[_Path] = []
    # Each stack item is a partial path: (nodes so far, resource at the tip, resource sum).
    stack = [([start], 1.0, 1.0)]
    while stack:
        nodes, resource, total = stack.pop()
        if len(nodes) - 1 >= max_hops:
            continue
        tip = nodes[-1]
        degree = graph.degree(tip) or 1
        flow = decay * resource / degree
        if flow < threshold:                    # early stopping (eq. 3)
            continue
        # Deterministic order: strongest edge first, ties broken by node id.
        neighbours = sorted(
            graph[tip].items(),
            key=lambda kv: (-float(kv[1].get("weight", 1.0) or 1.0), kv[0]),
        )
        for nxt, _attrs in neighbours:
            if nxt in nodes:                    # simple paths only
                continue
            extended = nodes + [nxt]
            acc = total + flow
            if nxt in targets:
                paths.append(_Path(nodes=extended, flow=acc / (len(extended) - 1),
                                   relevance=1.0))   # set by retrieve_paths
            stack.append((extended, flow, acc))
    return paths


def retrieve_paths(nodes: dict[str, float], max_paths: int = MAX_PATHS, decay: float = DECAY,
                   threshold: float = PRUNE_THRESHOLD, max_hops: int = MAX_HOPS) -> list[_Path]:
    """Key relational paths among the retrieved nodes, best first. Only the best path per node
    PAIR enters the pool (the paper's per-pair selection), so one densely connected pair cannot
    crowd out the rest of the query's structure.

    Paths are ranked by flow × relevance, NOT by flow alone. The paper ranks on flow because it
    assumes every retrieved node is relevant, leaving flow to discriminate how strongly two of
    them connect. That assumption breaks on this graph: since flow is split across a node's
    neighbours, a path between two LEAF nodes keeps almost all of it (degree 1 -> 1.70) while a
    path between the concepts that actually matter is penalized for being well connected (VHB,
    degree 23 -> 1.03; TAR, degree 210 -> 1.00). Ranking on flow alone therefore ordered the
    paths almost inversely to their clinical usefulness — «Pre-TAR Era -> Post-TAR Era» beat
    «TAF -> VHB» on an HBV question. Multiplying by the endpoints' cosine similarity to the
    question (already computed in `retrieve_nodes`) restores the paper's premise explicitly."""
    targets = set(nodes)
    best_per_pair: dict[tuple[str, str], _Path] = {}
    for start in nodes:
        for path in _flow_paths(start, targets - {start}, decay, threshold, max_hops):
            path.relevance = (nodes.get(path.nodes[0], 0.0)
                              + nodes.get(path.nodes[-1], 0.0)) / 2
            pair = tuple(sorted((path.nodes[0], path.nodes[-1])))
            current = best_per_pair.get(pair)
            if current is None or path.score > current.score:
                best_per_pair[pair] = path
    return heapq.nlargest(max_paths, best_per_pair.values(), key=lambda p: p.score)


def _path_chunk_ids(paths: list[_Path]) -> list[str]:
    """Chunk ids behind the paths, best-scoring path first. Both the nodes and the EDGES
    contribute: an edge's source chunk is the passage that stated the relation, which is often
    the one that actually answers a multi-hop question."""
    graph = _get_store().graph
    ordered: list[str] = []
    for path in paths:
        for i, node in enumerate(path.nodes):
            ordered.extend(_chunk_ids_of(graph.nodes[node]))
            if i + 1 < len(path.nodes):
                ordered.extend(_chunk_ids_of(graph.edges[node, path.nodes[i + 1]]))
    return ordered


def _describe(item, attrs: dict) -> str:
    """One readable description for a node/edge: the Spanish one when it has been generated,
    else LightRAG's original (English). LightRAG concatenates every extraction of the same
    item with its own separator, so we keep the first and trim it."""
    spanish = _get_store().desc_es.get(_item_key(item))
    if spanish:
        return " ".join(spanish.split())[:DESC_CHARS]
    raw = (attrs.get("description") or "").split(SEP)[0]
    return " ".join(raw.split())[:DESC_CHARS]


def format_paths(paths: list[_Path]) -> str:
    """Render the paths as the non-citable concept map (Spanish: it goes into the generation
    prompt). Ordered by ASCENDING score so the best path sits closest to the question at the
    end of the prompt — the paper's answer to the "lost in the middle" effect, adapted to our
    template (context first, question last).

    The scores themselves are deliberately NOT printed. They rank the paths, but a flow value
    is a topological quantity: shown to a clinical generator (or read off a trace by a doctor)
    a bare «1.70» invites reading it as confidence in the recommendation, which it is not.
    `path_scores` exposes them for tracing instead."""
    if not paths:
        return ""
    graph = _get_store().graph
    lines = []
    for path in sorted(paths, key=lambda p: p.score):
        parts = []
        for i, node in enumerate(path.nodes):
            desc = _describe(node, graph.nodes[node])
            parts.append(f"{node}: {desc}" if desc else node)
            if i + 1 < len(path.nodes):
                nxt = path.nodes[i + 1]
                parts.append(f"  --[{_describe((node, nxt), graph.edges[node, nxt])}]-->")
        lines.append("- " + "\n  ".join(parts))
    return "\n".join(lines)


def path_scores(paths: list[_Path]) -> list[dict]:
    """The ranking behind the concept map, for traces and debugging: which path won, and
    whether it won on graph structure (`flow`) or on closeness to the question (`relevance`).
    Best first — the reverse of the order they appear in the prompt."""
    return [{"path": " -> ".join(p.nodes), "score": round(p.score, 4),
             "flow": round(p.flow, 4), "relevance": round(p.relevance, 4)}
            for p in sorted(paths, key=lambda p: -p.score)]


# ---------------------------------------------------------------------------
# RETRIEVAL  (imported by the registry, the pipeline node and the evaluation)
# ---------------------------------------------------------------------------
def _trace_paths(query: str, paths: list[_Path]) -> None:
    """Record the path ranking in LangSmith as its own step, so a run can be inspected for WHY
    a path was chosen (the prompt only shows the resulting order). Silent no-op without
    tracing configured — it must never affect retrieval."""
    if not paths or not os.environ.get("LANGSMITH_API_KEY"):
        return
    try:
        from langsmith import traceable

        @traceable(name="pathrag_ranking", run_type="retriever")
        def _record(query: str) -> list[dict]:
            return path_scores(paths)

        _record(query)
    except Exception:
        pass



def pathrag_search_with_paths(query: str, top_k: int = 8, node_top_n: int = NODE_TOP_N,
                              max_paths: int = MAX_PATHS, decay: float = DECAY,
                              rewritten_query: str | None = None) -> tuple[list, str]:
    """Full PathRAG retrieval: keywords -> nodes -> pruned paths -> chunks + concept map.

    Returns (payloads, concept_map). The payloads are ordinary citable chunks; the concept map
    is the textual form of the same paths, for the generator to reason over but never quote.
    An empty graph result is not an error — `house_tail`'s hybrid complement still answers."""
    keywords = extract_keywords(query)
    nodes = retrieve_nodes(keywords, top_n=node_top_n)
    paths = retrieve_paths(nodes, max_paths=max_paths, decay=decay) if nodes else []
    _trace_paths(query, paths)
    primary = map_chunk_ids_to_payloads(_path_chunk_ids(paths))[:PRIMARY_CHUNK_CAP]
    return house_tail(query, primary, rewritten_query, top_k=top_k), format_paths(paths)


def pathrag_search(query: str, top_k: int = 8, rewritten_query: str | None = None) -> list:
    """Chunk-only entry point, honouring the retrieval contract shared by every mode (this is
    what the evaluation A/B calls, so all modes are compared on chunks alone)."""
    payloads, _ = pathrag_search_with_paths(query, top_k=top_k, rewritten_query=rewritten_query)
    return payloads


